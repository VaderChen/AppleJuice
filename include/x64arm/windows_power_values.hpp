using Guid=std::array<std::uint8_t,16>;
constexpr Guid guid(std::uint32_t first,std::uint16_t second,std::uint16_t third,std::array<std::uint8_t,8> tail){
    Guid out{};
    for(unsigned i=0;i<4;++i)out[i]=static_cast<std::uint8_t>(first>>(i*8));
    for(unsigned i=0;i<2;++i){out[4+i]=static_cast<std::uint8_t>(second>>(i*8));out[6+i]=static_cast<std::uint8_t>(third>>(i*8));}
    for(unsigned i=0;i<8;++i)out[8+i]=tail[i];
    return out;
}

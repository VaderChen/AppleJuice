#pragma once
#include "x64arm/windows_power_values.hpp"
namespace x64arm::power {
inline constexpr Guid acdc_source=guid(0x5d3e9a59,0xe9d5,0x4b00,{0xa6,0xbd,0xff,0x34,0xff,0x51,0x65,0x48});
inline constexpr Guid battery_remaining=guid(0xa7ad8041,0xb45a,0x4cae,{0x87,0xa3,0xee,0xcb,0xb4,0x68,0xa9,0xe1});
inline constexpr Guid console_display=guid(0x6fe69556,0x704a,0x47a0,{0x8f,0x24,0xc2,0x8d,0x93,0x6f,0xda,0x47});
inline constexpr Guid session_display=guid(0x2b84c20e,0xad23,0x4ddf,{0x93,0xdb,0x05,0xff,0xbd,0x7e,0xfc,0xa5});
inline constexpr Guid monitor_on=guid(0x02731015,0x4510,0x4526,{0x99,0xe6,0xe5,0xa1,0x7e,0xbd,0x1a,0xea});
inline constexpr Guid power_saving=guid(0xe00958c0,0xc213,0x4ace,{0xac,0x77,0xfe,0xcc,0xed,0x2e,0xee,0xa5});
inline constexpr Guid lid_switch=guid(0xba3e0f4d,0xb817,0x4094,{0xa2,0xd1,0xd5,0x63,0x79,0xe6,0xa0,0xf3});
inline constexpr std::array notification_settings{acdc_source,battery_remaining,power_saving,lid_switch,monitor_on,console_display,session_display};
inline std::optional<std::uint32_t> notification_value(const NativePowerNotificationSnapshot& snapshot,std::size_t setting){
    auto value=setting==0?snapshot.source:setting==1?snapshot.battery:setting==2?snapshot.saving:setting==3?snapshot.lid:snapshot.display;
    const auto maximum=setting==0?2U:setting==1?100U:setting>=4?2U:1U;
    if(setting>=notification_settings.size() || (value && *value>maximum))return {};
    if(setting==4 && value)value=*value!=0; // on／dim 均代表有電。
    return value;
}
}

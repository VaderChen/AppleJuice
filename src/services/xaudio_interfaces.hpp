struct ClassicClass {unsigned version,kind;};
inline std::optional<ClassicClass> classic_class(const GuestMemory& memory,std::uint64_t pointer){
    if(!pointer)return {};
    Guid id{};
    memory.read(GuestAddress{pointer},id);
    for(unsigned version=0;version<classic_guids.size();++version)
        for(unsigned kind=0;kind<classic_guids[version].size();++kind)
            if(id==classic_guids[version][kind])return ClassicClass{version,kind};
    if(id==reverb27_debug)return ClassicClass{7,2};
    if(id==meter27_debug)return ClassicClass{7,3};
    return {};
}
inline bool is_class(const GuestMemory& memory,std::uint64_t pointer){return classic_class(memory,pointer).has_value();}
